import type { TrafficEntry, ResultView, Language, MessageKey, TParams, ToolResult } from '@careloop/client';
import { t as translate } from '@careloop/client';

/** Which Alexa+ device class we are imitating, for the card panel width. */
export type DeviceClass = 'small' | 'large';
export type Theme = 'light' | 'dark';
export type TextSize = 'normal' | 'large';

export const DEVICE_LABEL: Record<DeviceClass, string> = {
  small: 'Small screen (≤10")',
  large: 'Large screen (≥11")',
};

/** One exchange in the simulated conversation. `spoken` is exactly what the tool
 *  returned in `content[0].text`, so what the speaker says and what the screen shows
 *  are the same string — never a second generated copy. */
export interface Turn {
  id: string;
  said: string;
  /** What our deterministic stand-in for Alexa's own model understood. */
  read: string;
  tool: string;
  args: Record<string, unknown>;
  spoken: string;
  view: ResultView;
  ms: number;
  at: number;
  isError: boolean;
  /** Index in view.items the phrase pointed at, or -1. */
  highlight: number;
  /** True while the call is in flight. */
  pending: boolean;
  /** True for a turn we generated by replaying a sample visit. */
  replay: boolean;
  /** True for companion-side bookkeeping turns (a capture summary). These never drive
   *  the card rail and are never spoken. */
  infoOnly?: boolean;
  /** The untouched tool result, kept so the Device Lab can build an envelope and count masked
   *  fields. Nothing renders from it directly — the card still goes through `toView()`. */
  raw?: ToolResult;
}

const TOGGLE_KEY = 'careloop.simulator.toggles.v1';

interface SavedToggles {
  device: DeviceClass;
  theme: Theme;
  text: TextSize;
  tts: boolean;
  autoRefresh: boolean;
  lang: Language;
}

function defaults(): SavedToggles {
  const prefersDark = typeof window !== 'undefined'
    && typeof window.matchMedia === 'function'
    && window.matchMedia('(prefers-color-scheme: dark)').matches;
  return { device: 'large', theme: prefersDark ? 'dark' : 'light', text: 'normal', tts: true, autoRefresh: false, lang: 'en' };
}

function load(): SavedToggles {
  const base = defaults();
  if (typeof window === 'undefined') return base;
  try {
    const raw = window.localStorage.getItem(TOGGLE_KEY);
    if (!raw) return base;
    const got = JSON.parse(raw) as Partial<SavedToggles>;
    return {
      device: got.device === 'small' ? 'small' : 'large',
      theme: got.theme === 'dark' ? 'dark' : 'light',
      text: got.text === 'large' ? 'large' : 'normal',
      tts: got.tts !== false,
      autoRefresh: got.autoRefresh === true,
      lang: got.lang === 'hi' || got.lang === 'pa' ? got.lang : 'en',
    };
  } catch {
    return base;
  }
}

const saved = load();

/** Module-level session state (Svelte 5 runes in a .svelte.ts module). The toggles are
 *  mirrored onto <html> so the shared CSS tokens can react to them. */
export const session = $state({
  turns: [] as Turn[],
  traffic: [] as TrafficEntry[],
  people: [] as string[],

  device: saved.device,
  theme: saved.theme,
  text: saved.text,
  tts: saved.tts,
  autoRefresh: saved.autoRefresh,
  lang: saved.lang,

  trafficOpen: false,
  pollPaused: false,
});

function persist(): void {
  if (typeof window === 'undefined') return;
  try {
    window.localStorage.setItem(TOGGLE_KEY, JSON.stringify({
      device: session.device, theme: session.theme, text: session.text,
      tts: session.tts, autoRefresh: session.autoRefresh, lang: session.lang,
    } satisfies SavedToggles));
  } catch {
    /* private mode — toggles simply do not survive a reload */
  }
}

export function setDevice(value: DeviceClass): void {
  session.device = value;
  persist();
}

export function setTheme(value: Theme): void {
  session.theme = value;
  persist();
}

export function setTextSize(value: TextSize): void {
  session.text = value;
  persist();
}

export function setTts(value: boolean): void {
  session.tts = value;
  persist();
}

export function setAutoRefresh(value: boolean): void {
  session.autoRefresh = value;
  persist();
}

export function setLanguage(value: Language): void {
  session.lang = value;
  persist();
}

/** Translate a CHROME message key in the current session language. Health text never goes
 *  through here — those strings live on the ResultView, straight from the server. Because it
 *  reads `session.lang` (a rune) the caller re-renders when the language changes. */
export function tt(key: MessageKey, params: TParams = {}): string {
  return translate(session.lang, key, params);
}

export function toggleTrafficOpen(open?: boolean): void {
  session.trafficOpen = open ?? !session.trafficOpen;
}

/** Traffic is append-only and capped so a long demo cannot exhaust memory. */
const TRAFFIC_CAP = 300;

export function pushTraffic(entry: TrafficEntry): void {
  session.traffic.push(entry);
  if (session.traffic.length > TRAFFIC_CAP) {
    session.traffic.splice(0, session.traffic.length - TRAFFIC_CAP);
  }
}

export function clearTraffic(): void {
  session.traffic.length = 0;
}

let turnSeq = 0;

export function newTurnId(): string {
  return `t-${Date.now().toString(36)}-${turnSeq++}`;
}

export function addTurn(turn: Turn): Turn {
  session.turns.push(turn);
  return turn;
}

/** Patch a turn in place (Svelte reactivity needs the object itself to change). */
export function patchTurn(id: string, patch: Partial<Turn>): void {
  const i = session.turns.findIndex((t) => t.id === id);
  if (i < 0) return;
  session.turns[i] = { ...session.turns[i], ...patch };
}

export function clearTurns(): void {
  session.turns.length = 0;
}

export function lastCompletedTurn(): Turn | undefined {
  for (let i = session.turns.length - 1; i >= 0; i--) {
    if (!session.turns[i].pending) return session.turns[i];
  }
  return undefined;
}
