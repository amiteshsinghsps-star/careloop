#!/usr/bin/env python3
"""gen_contracts — the machine-readable contract layer (PRD Part O engineering standard).

One source of truth: `TOOL_DEFS` in careloop/tools.py. This script IMPORTS that list
(no HTTP, no server start, no third-party deps) and projects it into:

  artifacts/contracts/<tool>.schema.json   one file per MCP tool: name, description, inputSchema,
                                 outputSchema and the declarative hints the defs really
                                 carry — `annotations` (readOnlyHint / destructiveHint /
                                 idempotentHint), `guest_safe`, `ui` and `action`.
  artifacts/contracts/index.json           tool count + sha256 over the canonicalised contract set,
                                 plus each file's own sha256. Docs and tests quote these.
  frontend/client/src/contracts.ts
                                 the same facts for TypeScript: the tool names as a const
                                 tuple and the manifest hashes, so a frontend can assert
                                 against the real server contract instead of a copy.

Byte-stable by construction: keys sorted, 2-space indent, LF newlines, trailing newline,
no timestamps and nothing else that varies between runs — so the drift test in
tests/test_contracts.py compares bytes and nothing else.

    python scripts/gen_contracts.py            # write
    python scripts/gen_contracts.py --check    # verify only, exit 1 + name the file (CI)
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from careloop import tools                                   # noqa: E402

INDEX_NAME = "index.json"
GENERATOR = "scripts/gen_contracts.py"


def canonical(obj) -> str:
    """The one serialisation: sorted keys, 2-space indent, unicode kept literal."""
    return json.dumps(obj, sort_keys=True, indent=2, ensure_ascii=False)


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def contract_for(defn: dict) -> dict:
    """A faithful projection of one TOOL_DEFS entry — every key below exists in the def."""
    return {
        "name": defn["name"],
        "description": defn["description"],
        "inputSchema": defn["inputSchema"],
        "outputSchema": defn["outputSchema"],
        "annotations": defn.get("annotations", {}),
        "guest_safe": bool(defn.get("guest_safe")),
        "ui": bool(defn.get("ui")),
        "action": defn.get("action"),
    }


def build_contracts() -> list:
    """Every tool, sorted by name so the set is order-independent."""
    return sorted((contract_for(d) for d in tools.TOOL_DEFS), key=lambda c: c["name"])


def set_manifest_sha256(entries: list) -> str:
    """sha256 over the canonicalised contract set: each file's own hash, name-ordered."""
    canonical_set = "\n".join(f"{e['name']}:{e['sha256']}" for e in entries) + "\n"
    return sha256_text(canonical_set)


def render() -> dict:
    """{repo-relative path: exact bytes} for every file this generator owns."""
    contracts = build_contracts()
    entries = []
    files = {}
    for c in contracts:
        name = c["name"]
        fname = f"{name}.schema.json"
        text = canonical(c) + "\n"
        files[f"artifacts/contracts/{fname}"] = text
        entries.append({"name": name, "file": fname, "sha256": sha256_text(text),
                        "annotations": c["annotations"], "guest_safe": c["guest_safe"],
                        "ui": c["ui"]})

    manifest = set_manifest_sha256(entries)
    index = {
        "kind": "careloop-tool-contracts",
        "generated_by": GENERATOR,
        "source_of_truth": "careloop/tools.py TOOL_DEFS",
        "tool_count": len(entries),
        "manifest_sha256": manifest,
        # the hash the running server publishes for the wire contract it assembles from the
        # same defs (careloop/tools.py manifest_hash) -- quoted by /api/diagnostics
        "wire_manifest_hash": tools.manifest_hash(),
        "tools": entries,
    }
    files[f"artifacts/contracts/{INDEX_NAME}"] = canonical(index) + "\n"
    files["frontend/client/src/contracts.ts"] = render_ts(entries, manifest, index)
    return files


def render_ts(entries: list, manifest: str, index: dict) -> str:
    names = [e["name"] for e in entries]
    guest = [e["name"] for e in entries if e["guest_safe"]]
    ui = [e["name"] for e in entries if e["ui"]]

    def tuple_of(xs):
        """A TS const tuple: multi-line when non-empty, `[]` when empty."""
        if not xs:
            return "[]"
        return "[" + "".join(f"\n  '{n}'," for n in xs) + "\n]"

    ts = f"""/* contracts.ts — GENERATED by {GENERATOR}; do not edit by hand.
   Source of truth: TOOL_DEFS in careloop/tools.py. Regenerate with:
       python {GENERATOR}
   Drift is a CI failure (tests/test_contracts.py), so these names and hashes are the
   server's real contract — nothing here is a hand-written description of it. */

/** Every MCP tool the server declares, in name order. */
export const TOOL_NAMES = {tuple_of(names)} as const;

export type ToolName = (typeof TOOL_NAMES)[number];

/** Tools runnable for an unauthenticated guest (read-only by construction). */
export const GUEST_SAFE_TOOLS = {tuple_of(guest)} as const;

/** Tools that render the structured result on a UI surface (the MCP card). */
export const UI_TOOLS = {tuple_of(ui)} as const;

/** The number of declared tools — the same count artifacts/contracts/index.json records. */
export const TOOL_COUNT = {len(names)};

/** sha256 over the canonicalised contract set (artifacts/contracts/*.schema.json, name-ordered). */
export const CONTRACTS_MANIFEST_SHA256 = '{manifest}';

/** sha256 of the wire contract careloop/tools.py `manifest_hash()` publishes. */
export const WIRE_MANIFEST_SHA256 = '{index["wire_manifest_hash"]}';

/** Narrow to a declared tool name, or return null — for client-side assertion. */
export function asToolName(value: string): ToolName | null {{
  return (TOOL_NAMES as readonly string[]).includes(value) ? (value as ToolName) : null;
}}
"""
    return ts


def committed(files: dict):
    """(mismatches, stale files): what differs between the repo and `files`."""
    bad = []
    for rel, text in sorted(files.items()):
        path = os.path.join(ROOT, *rel.split("/"))
        want = text.encode("utf-8")
        try:
            with open(path, "rb") as fh:
                got = fh.read()
        except OSError:
            got = None
        if got != want:
            bad.append((rel, got, want))
    extra = []
    cdir = os.path.join(ROOT, "artifacts", "contracts")
    if os.path.isdir(cdir):
        expected = {rel.split("/")[-1] for rel in files if rel.startswith("artifacts/contracts/")}
        extra = sorted(n for n in os.listdir(cdir) if n.endswith(".json") and n not in expected)
    return bad, extra


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="verify the committed files match, write nothing (CI-friendly)")
    ap.add_argument("--out", metavar="DIR",
                    help="write the contract set into DIR instead of the repo (drift test)")
    args = ap.parse_args(argv)

    files = render()

    if args.out:
        for rel, text in files.items():
            target = os.path.join(args.out, *rel.split("/"))
            os.makedirs(os.path.dirname(target), exist_ok=True)
            with open(target, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
        print(f"{args.out}: {len(files)} files written (artifacts/contracts/ + frontend/client)")
        return 0

    if args.check:
        mismatches, extra = committed(files)
        if mismatches or extra:
            print(f"CONTRACT DRIFT -- committed files do not match what {GENERATOR} produces")
            print(f"from careloop/tools.py. Run: python {GENERATOR}\n")
            for rel, got, want in mismatches:
                reason = "missing" if got is None else "different bytes"
                print(f"  - {rel}: {reason}")
            for name in extra:
                print(f"  - artifacts/contracts/{name}: not produced by the generator (stale file?)")
            return 1
        n = sum(1 for rel in files if rel.startswith("artifacts/contracts/") and rel != f"artifacts/contracts/{INDEX_NAME}")
        print(f"contracts ok: {n} tool schemas, manifest "
              f"{committed_manifest(files)} ({GENERATOR} --check)")
        return 0

    written = 0
    for rel, text in files.items():
        path = os.path.join(ROOT, *rel.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        written += 1
    tools_n = sum(1 for rel in files if rel.endswith(".schema.json"))
    print(f"wrote {written} files: {tools_n} tool schemas + {INDEX_NAME} + contracts.ts, "
          f"manifest {committed_manifest(files)}")
    return 0


def committed_manifest(files: dict) -> str:
    import re
    index = files.get(f"artifacts/contracts/{INDEX_NAME}") or ""
    m = re.search(r'"manifest_sha256":\s*"([0-9a-f]{64})"', index)
    return m.group(1) if m else "(none)"


if __name__ == "__main__":
    sys.exit(main())
